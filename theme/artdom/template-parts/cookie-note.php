<?php
/**
 * Плашка про файлы cookie.
 *
 * Уведомление, а не диалог: страницу не затемняет и ничего не блокирует.
 * У образцов, с которых снято построение (poedimdostavka.ru и второй пример
 * заказчика), подложка закрывает весь экран — читать сайт нельзя, пока не
 * ткнёшь. Для информационного сообщения это перебор, приём не взят.
 *
 * ДВА СОСТОЯНИЯ, и выбирает их номер счётчика в настройках:
 *
 *   номера нет  — сайт не отслеживает ничего. Текст говорит это прямо,
 *                 кнопка одна: отказываться не от чего.
 *   номер есть  — текст про аналитику и ДВЕ кнопки. Счётчик подключается
 *                 только после «Принять» (см. inc/artdom-analytics.php);
 *                 отказ запоминается так же, как согласие, и второй раз
 *                 человека не спрашивают.
 *
 * Так сделано ради передачи сайта: заказчик вписывает номер в админке, и
 * согласие начинает работать само. Иначе он поставил бы Метрику в <head>,
 * как в обоих образцах, где счётчик отрабатывает ДО нажатия и кнопка ничего
 * не решает.
 *
 * @package artdom
 */

/* Ссылка ведёт на документ ПРО COOKIE, а не на первый попавшийся правовой.
   Раньше здесь стоял $legal[0] — то есть политика конфиденциальности: в
   плашке про cookie ссылка «Подробнее» открывала документ про персональные
   данные, где про cookie не сказано ни слова.
   Ищем по адресу, а не по названию: название заказчик волен переписать, а
   адрес страницы задаётся один раз. Не нашли — откатываемся на первый
   документ, чтобы ссылка не исчезла вовсе. */
$legal   = artdom_field( 'opt_legal', true );
$privacy = '';
if ( is_array( $legal ) ) {
	foreach ( $legal as $artdom_док ) {
		if ( ! empty( $artdom_док['url'] ) && false !== strpos( $artdom_док['url'], '/cookie' ) ) {
			$privacy = $artdom_док['url'];
			break;
		}
	}
	if ( '' === $privacy && ! empty( $legal[0]['url'] ) ) {
		$privacy = $legal[0]['url'];
	}
}

$counter = artdom_metrika_id();

/* Своё поле выигрывает всегда — заказчик мог переписать формулировку.
   Пусто — берём запасной текст под текущее состояние сайта. Читаем поле
   напрямую, а не через artdom_field(): та подставила бы запасной вариант
   раньше, чем мы решим, какой из двух нужен. */
$own  = function_exists( 'get_field' ) ? trim( (string) get_field( 'cookie_text', 'option' ) ) : '';
$text = '' !== $own ? $own : artdom_default( $counter ? 'cookie_text_analytics' : 'cookie_text' );
?>
<?php
/* 21.09.2026. Построение снято с afternow.co (плагин Complianz): капсула в
   правом нижнем углу, полупрозрачный фон с размытием, кнопки в строку.
   Числа сняты с образца щупом и перенесены в стили как есть, в пикселях;
   типографика при этом наша, по токенам сайта.

   Кнопки «Настроить» и списка категорий здесь БОЛЬШЕ НЕТ — убраны по
   просьбе заказчика в тот же день. Выбор из двух кнопок закрывает всё, что
   сайту нужно: согласие включает счётчик, отказ его не включает и больше не
   переспрашивает. Подробности — что именно хранится и как отключить
   остальное — лежат на странице по ссылке «Подробнее», а не в плашке. */
?>
<aside class="cookie" data-cookie hidden aria-label="Про файлы cookie">
  <div class="cookie__row">
    <p class="cookie__text">
      <?php echo esc_html( $text ); ?>
      <?php if ( $privacy ) : ?>
      <a class="selectable" href="<?php echo esc_url( $privacy ); ?>"><?php echo esc_html( artdom_field( 'cookie_link', true ) ); ?></a>
      <?php endif; ?>
    </p>
    <div class="cookie__acts">
      <button class="cookie__btn cookie__btn--yes" type="button" data-cookie-ok>
        <?php echo esc_html( artdom_field( $counter ? 'cookie_btn_yes' : 'cookie_btn', true ) ); ?>
      </button>
      <button class="cookie__btn" type="button" data-cookie-no>
        <?php echo esc_html( artdom_field( 'cookie_btn_no', true ) ); ?>
      </button>
    </div>
  </div>
</aside>
