/**
 * Перевести страницу «О компании» на свой шаблон и заполнить блоки.
 *
 * Заполненное не трогаем: правки заказчика дороже наших примеров.
 *
 * @param int $page_id Идентификатор страницы.
 */
function artdom_fill_about( $page_id ) {
	if ( ! $page_id || ! function_exists( 'update_field' ) ) {
		return;
	}

	update_post_meta( $page_id, '_wp_page_template', 'templates/template-about.php' );

	$data = artdom_demo_about();

	foreach ( array( 'ab_intro_title', 'ab_intro_text', 'ab_principles_title', 'ab_path_title', 'ab_team_title', 'ab_team_lead' ) as $key ) {
		if ( ! get_field( $key, $page_id ) ) {
			update_field( 'field_artdom_' . $key, $data[ $key ], $page_id );
		}
	}

	if ( ! get_field( 'ab_principles', $page_id ) ) {
		update_field(
			'field_artdom_ab_principles',
			array_map(
				static function ( $p ) {
					return array( 'field_artdom_pr_title' => $p[0], 'field_artdom_pr_text' => $p[1] );
				},
				$data['ab_principles']
			),
			$page_id
		);
	}

	if ( ! get_field( 'ab_path', $page_id ) ) {
		update_field(
			'field_artdom_ab_path',
			array_map(
				static function ( $p ) {
					return array( 'field_artdom_pt_year' => $p[0], 'field_artdom_pt_title' => $p[1], 'field_artdom_pt_text' => $p[2] );
				},
				$data['ab_path']
			),
			$page_id
		);
	}

	if ( ! get_field( 'ab_team', $page_id ) ) {
		update_field(
			'field_artdom_ab_team',
			array_map(
				static function ( $p ) {
					return array( 'field_artdom_tm_name' => $p[0], 'field_artdom_tm_role' => $p[1], 'field_artdom_tm_note' => $p[2] );
				},
				$data['ab_team']
			),
			$page_id
		);
	}

	/* Длинный текст из содержимого страницы больше не нужен: он разложен по
	   блокам. Оставляем только раздел «Чем занимаемся», если он там был. */
	$post = get_post( $page_id );
	if ( $post && false !== mb_strpos( (string) $post->post_content, 'Как мы работаем' ) ) {
		wp_update_post( array( 'ID' => $page_id, 'post_content' => '' ) );
	}
}
