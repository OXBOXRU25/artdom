/**
 * Создать всё недостающее: объекты, отзывы, услуги, страницы, меню.
 *
 * Идемпотентно: наличие проверяется по ярлыку или заголовку, поэтому повторный
 * запуск ничего не дублирует.
 */
function artdom_fill_demo() {
	$made = array( 'objects' => 0, 'reviews' => 0, 'services' => 0, 'pages' => 0, 'posts' => 0 );

	if ( ! function_exists( 'update_field' ) ) {
		return $made;
	}

	$thumb = function_exists( 'artdom_demo_image' ) ? artdom_demo_image( 'object.webp' ) : 0;

	/* --- Объекты --- */
	foreach ( artdom_demo_objects() as $i => $o ) {
		if ( get_page_by_path( sanitize_title( $o['title'] ), OBJECT, 'artdom_object' ) ) {
			continue;
		}
		$id = wp_insert_post(
			array(
				'post_type'   => 'artdom_object',
				'post_title'  => $o['title'],
				'post_name'   => sanitize_title( $o['title'] ),
				'post_status' => 'publish',
				'menu_order'  => $i,
			)
		);
		if ( is_wp_error( $id ) ) {
			continue;
		}

		wp_set_object_terms( $id, $o['terms'], 'artdom_object_type' );

		update_field( 'field_artdom_obj_year', $o['year'], $id );
		update_field( 'field_artdom_obj_price', $o['price'], $id );
		update_field( 'field_artdom_obj_price_num', $o['price_n'], $id );
		update_field( 'field_artdom_obj_area', $o['area'], $id );
		update_field( 'field_artdom_obj_rooms', $o['rooms'], $id );
		update_field( 'field_artdom_obj_floor', $o['floor'], $id );
		update_field( 'field_artdom_obj_district', $o['district'], $id );
		update_field( 'field_artdom_obj_metro', $o['metro'], $id );
		update_field( 'field_artdom_obj_complex', $o['complex'], $id );
		update_field( 'field_artdom_obj_address', $o['address'], $id );
		update_field( 'field_artdom_obj_text', $o['text'], $id );

		/* Короткие факты для карточки: то же, что человек читает первым. */
		$facts = array(
			array( 'field_artdom_of_value' => $o['area'] . ' м²' ),
			array( 'field_artdom_of_value' => $o['rooms'] . ' ' . artdom_plural( $o['rooms'], array( 'спальня', 'спальни', 'спален' ) ) ),
			array( 'field_artdom_of_value' => $o['floor'] ),
		);
		update_field( 'field_artdom_obj_facts', $facts, $id );

		if ( $thumb ) {
			set_post_thumbnail( $id, $thumb );
		}
		++$made['objects'];
	}

	/* --- Отзывы --- */
	foreach ( artdom_demo_reviews() as $i => $r ) {
		list( $name, $source, $rating, $body ) = $r;
		if ( get_page_by_path( sanitize_title( $name ), OBJECT, 'artdom_review' ) ) {
			continue;
		}
		$id = wp_insert_post(
			array(
				'post_type'   => 'artdom_review',
				'post_title'  => $name,
				'post_name'   => sanitize_title( $name ),
				'post_status' => 'publish',
				'menu_order'  => $i,
			)
		);
		if ( is_wp_error( $id ) ) {
			continue;
		}
		update_field( 'field_artdom_rev_source', $source, $id );
		update_field( 'field_artdom_rev_rating', $rating, $id );
		update_field( 'field_artdom_rev_text', $body, $id );
		++$made['reviews'];
	}

	/* --- Услуги --- */
	foreach ( artdom_demo_services() as $i => $s ) {
		if ( get_page_by_path( sanitize_title( $s['title'] ), OBJECT, 'artdom_service' ) ) {
			continue;
		}
		$id = wp_insert_post(
			array(
				'post_type'   => 'artdom_service',
				'post_title'  => $s['title'],
				'post_name'   => sanitize_title( $s['title'] ),
				'post_status' => 'publish',
				'menu_order'  => $i,
			)
		);
		if ( is_wp_error( $id ) ) {
			continue;
		}
		update_field( 'field_artdom_svc_lead', $s['lead'], $id );
		update_field( 'field_artdom_svc_text', $s['text'], $id );
		update_field(
			'field_artdom_svc_steps',
			array_map(
				static function ( $st ) {
					return array( 'field_artdom_ss_title' => $st[0], 'field_artdom_ss_text' => $st[1] );
				},
				$s['steps']
			),
			$id
		);
		update_field(
			'field_artdom_svc_faq',
			array_map(
				static function ( $q ) {
					return array( 'field_artdom_faq_q' => $q[0], 'field_artdom_faq_a' => $q[1] );
				},
				$s['faq']
			),
			$id
		);
		++$made['pages'];
		++$made['services'];
	}

	/* --- Страницы --- */
	$pages = array();
	foreach ( artdom_demo_pages() as $p ) {
		$existing = get_page_by_path( $p['slug'] );
		if ( $existing ) {
			$pages[ $p['slug'] ] = $existing->ID;
			continue;
		}
		$id = wp_insert_post(
			array(
				'post_type'    => 'page',
				'post_title'   => $p['title'],
				'post_name'    => $p['slug'],
				'post_excerpt' => $p['excerpt'],
				'post_content' => $p['content'],
				'post_status'  => 'publish',
			)
		);
		if ( is_wp_error( $id ) ) {
			continue;
		}
		if ( $p['template'] ) {
			update_post_meta( $id, '_wp_page_template', $p['template'] );
		}
		$pages[ $p['slug'] ] = $id;
		++$made['pages'];
	}

	/* --- Записи блога --- */
	foreach ( artdom_demo_posts() as $i => $p ) {
		if ( get_page_by_path( sanitize_title( $p['title'] ), OBJECT, 'post' ) ) {
			continue;
		}
		$id = wp_insert_post(
			array(
				'post_type'    => 'post',
				'post_title'   => $p['title'],
				'post_name'    => sanitize_title( $p['title'] ),
				'post_excerpt' => $p['excerpt'],
				'post_content' => $p['content'],
				'post_status'  => 'publish',
				/* Разносим по датам, иначе все четыре встают одной минутой и
				   лента сортируется как попало. */
				'post_date'    => gmdate( 'Y-m-d H:i:s', strtotime( '-' . ( $i * 9 + 3 ) . ' days' ) ),
			)
		);
		if ( ! is_wp_error( $id ) ) {
			++$made['posts'];
		}
	}

	/* Страница для ленты записей. Без неё у блога нет адреса: WordPress
	   отдаёт записи на главной, а главная у нас — лендинг. */
	if ( isset( $pages['blog'] ) ) {
		update_option( 'page_for_posts', (int) $pages['blog'] );
	}

	artdom_build_menus( $pages );
	artdom_fill_options( $pages );
	artdom_fill_about( isset( $pages['about'] ) ? $pages['about'] : 0 );

	return $made;
}

/**
 * Меню из настоящих разделов.
 *
 * Якорные ссылки годились, пока сайт был одной страницей. У коммерческого
 * сайта в меню должны стоять адреса разделов, иначе с внутренней страницы
 * навигация ведёт в никуда.
 *
 * @param array $pages Ярлык страницы => идентификатор.
 */
function artdom_build_menus( $pages ) {
	$items = array(
		array( 'Объекты', get_post_type_archive_link( 'artdom_object' ) ),
		array( 'Услуги', get_post_type_archive_link( 'artdom_service' ) ),
		array( 'О компании', isset( $pages['about'] ) ? get_permalink( $pages['about'] ) : '' ),
		array( 'Отзывы', get_post_type_archive_link( 'artdom_review' ) ),
		array( 'Блог', isset( $pages['blog'] ) ? get_permalink( $pages['blog'] ) : '' ),
		array( 'Контакты', isset( $pages['contacts'] ) ? get_permalink( $pages['contacts'] ) : '' ),
	);

	foreach ( array( 'menu_main' => 'Главное', 'menu_footer' => 'В подвале' ) as $location => $name ) {
		$menu = wp_get_nav_menu_object( $name );
		if ( ! $menu ) {
			$menu_id = wp_create_nav_menu( $name );
			if ( is_wp_error( $menu_id ) ) {
				continue;
			}
		} else {
			$menu_id = (int) $menu->term_id;
		}

		/* Пункт с таким названием мог остаться от прежней версии сайта и вести
		   на якорь #objects. Такой не пропускаем, а переписываем: иначе меню
		   навсегда останется лендинговым. */
		$existing = wp_get_nav_menu_items( $menu_id );
		$by_title = array();
		if ( $existing ) {
			foreach ( $existing as $item ) {
				$by_title[ $item->title ] = (int) $item->ID;
			}
		}

		foreach ( $items as $i => $item ) {
			list( $title, $url ) = $item;
			if ( ! $url ) {
				continue;
			}
			wp_update_nav_menu_item(
				$menu_id,
				isset( $by_title[ $title ] ) ? $by_title[ $title ] : 0,
				array(
					'menu-item-title'    => $title,
					'menu-item-url'      => $url,
					'menu-item-status'   => 'publish',
					'menu-item-position' => $i + 1,
				)
			);
		}

		$locations = get_theme_mod( 'nav_menu_locations', array() );
		if ( empty( $locations[ $location ] ) ) {
			$locations[ $location ] = $menu_id;
			set_theme_mod( 'nav_menu_locations', $locations );
		}
	}
}

