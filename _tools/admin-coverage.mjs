console.log('\n── 2. ПОЛЕ В АДМИНКЕ ЕСТЬ, НО НА САЙТ НЕ ВЫВОДИТСЯ (' + нетВыводa.length + ') ──');
console.log('   Заполнит — ничего не изменится. Хуже пустого поля.');
for (const к of нетВыводa) console.log('   ' + ш(к, 26) + поляADM.get(к));

console.log('\n── 3б. ПОЛЕ ОБЩИХ НАСТРОЕК ЧИТАЮТ БЕЗ option (' + безOption.length + ') ──');
console.log('   Заказчик правит поле, сохраняет — на сайте остаётся старое.');
for (const о of безOption) console.log('   ' + ш(о.ключ, 24) + о.файл + ':' + о.строка);

console.log('\n── 3. ТЕКСТ ЗАШИТ В ШАБЛОН МИМО ПОЛЕЙ ──');
const контент = зашито.filter((з) => !з.служебное);
const служ = зашито.filter((з) => з.служебное);
console.log('   видимый текст: ' + контент.length + ' мест, подписи и alt: ' + служ.length + ' мест');
const поФайлам = new Map();
for (const з of контент) {
  if (!поФайлам.has(з.файл)) поФайлам.set(з.файл, []);
  поФайлам.get(з.файл).push(з);
}
for (const [ф, сп] of [...поФайлам.entries()].sort((a, b) => b[1].length - a[1].length)) {
  console.log('\n   ' + ф + '  (' + сп.length + ')');
  for (const з of сп.slice(0, 12)) console.log('      ' + ш(з.строка, 5) + з.текст);
  if (сп.length > 12) console.log('      … ещё ' + (сп.length - 12));
}
