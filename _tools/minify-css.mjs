/* Сжатие стилей темы. Без сторонних пакетов: ставить минификатор из сети ради
   одного файла дороже, чем написать посимвольный проход.

   Проход именно посимвольный, а не регулярками: в CSS есть строки в кавычках
   и url(), внутри которых последовательность «/*» — обычные символы, и
   регулярка вырезала бы кусок правила. Здесь мы всегда знаем, где находимся.

   Что делает: убирает комментарии, схлопывает пробелы, снимает пробелы вокруг
   служебных знаков и последнюю точку с запятой перед скобкой.
   Чего НЕ делает: не трогает порядок правил, не объединяет селекторы и не
   переписывает значения — то есть не может изменить вид страницы.

   Запуск:  node _tools/minify-css.mjs
*/
import fs from 'node:fs';
import path from 'node:path';

const src = 'D:/AI/Artdom/wp/wp-content/themes/artdom/css/style.css';
const out = src.replace(/\.css$/, '.min.css');

const css = fs.readFileSync(src, 'utf8');
let r = '';
let i = 0;

while (i < css.length) {
  const c = css[i];

  /* Строка в кавычках — переносим как есть вместе с экранированием. */
  if (c === '"' || c === "'") {
    const quote = c;
    r += c; i++;
    while (i < css.length) {
      if (css[i] === '\\') { r += css[i] + (css[i + 1] || ''); i += 2; continue; }
      r += css[i];
      if (css[i] === quote) { i++; break; }
      i++;
    }
    continue;
  }

  /* Комментарий — выбрасываем целиком. */
  if (c === '/' && css[i + 1] === '*') {
    const end = css.indexOf('*/', i + 2);
    i = end === -1 ? css.length : end + 2;
    /* Комментарий часто стоит между правилами: чтобы селекторы не слиплись,
       оставляем на его месте один пробел — лишний уберёт следующий шаг. */
    r += ' ';
    continue;
  }

  /* Любая цепочка пробелов и переносов — один пробел. */
  if (/\s/.test(c)) {
    while (i < css.length && /\s/.test(css[i])) i++;
    r += ' ';
    continue;
  }

  r += c; i++;
}

/* Пробелы вокруг служебных знаков не нужны.

   ВАЖНО: «+» и «~» в этот список НЕ входят, хотя они и комбинаторы
   селекторов. В calc() пробелы вокруг «+» обязательны по стандарту, и без
   них всё правило становится недействительным. Ровно это я и сделал первым
   заходом: у липкого блока цены пропало смещение, у галереи — обнуление
   отступа, у кнопок сломался перекат текста. Три разных симптома от одной
   строки. Экономия на этих пробелах — байты, цена — сломанная страница. */
r = r
  .replace(/\s*([{};,>])\s*/g, '$1')
  /* Двоеточие обрабатываем отдельно и только СПРАВА: пробел ПЕРЕД ним несёт
     смысл. «.menu[data-open] :where(...)» — это потомок, а без пробела —
     сам элемент, и правило не срабатывает никогда. Так у меня пропало всё
     содержимое бургер-меню: пункты остались прозрачными. */
  .replace(/:\s+/g, ':')
  .replace(/;}/g, '}')
  .trim();

/* Щуп на ту самую поломку: в calc() знак «+» обязан быть окружён пробелами,
   иначе правило целиком становится недействительным. Проверка стоит здесь, а
   не в голове: сжатие правится редко, а забывается быстро, и следующая
   правка регулярки без неё прошла бы молча. Файл при находке не пишется —
   лучше остаться без сжатия, чем со сломанными стилями. */
const плохие = (r.match(/calc\([^;{}]*[0-9a-z%)]\+/gi) || []).length;
if (плохие) {
  console.error('ОШИБКА: в calc() пропал пробел перед «+», случаев: ' + плохие + '. Файл не записан.');
  process.exit(1);
}

/* Второй щуп, на второй мой промах. Пробел перед двоеточием разделяет предка
   и потомка: «.menu[data-open] :where(...)» — это «внутри меню», а без
   пробела — «само меню и есть эта ссылка», чего не бывает никогда. Правило
   умирает молча, без единой ошибки в консоли: у меня так пропало всё
   содержимое бургер-меню. Считаем такие места до и после. */
const пара = /[\]a-z0-9)] :[a-z]/gi;
const было = (css.match(пара) || []).length;
const стало = (r.match(пара) || []).length;
if (стало < было) {
  console.error('ОШИБКА: пропал пробел перед «:» в селекторе-потомке, случаев: ' + (было - стало) + '. Файл не записан.');
  process.exit(1);
}

fs.writeFileSync(out, r);
const was = Buffer.byteLength(css), now = Buffer.byteLength(r);
console.log(path.basename(out) + ': ' + was + ' -> ' + now + ' б (' + Math.round((1 - now / was) * 100) + '% меньше)');
