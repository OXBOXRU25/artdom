/* Сжатие стилей темы. Без сторонних пакетов: ставить минификатор из сети ради
   одного файла дороже, чем написать посимвольный проход.

   Проход именно посимвольный, а не регулярками: в CSS есть строки в кавычках
   и url(), внутри которых последовательность «/*» — обычные символы, и
   регулярка вырезала бы кусок правила. Здесь мы всегда знаем, где находимся.

   Что делает: убирает комментарии, схлопывает пробелы, снимает пробелы вокруг
   служебных знаков и последнюю точку с запятой перед скобкой.
   Чего НЕ делает: не трогает порядок правил, не объединяет селекторы и не
   переписывает значения — то есть не может изменить вид страницы.

   Запуск:  node _tools/minify-css.mjs
*/
import fs from 'node:fs';
import path from 'node:path';

const src = 'D:/AI/Artdom/wp/wp-content/themes/artdom/css/style.css';
const out = src.replace(/\.css$/, '.min.css');

const css = fs.readFileSync(src, 'utf8');
let r = '';
let i = 0;

while (i < css.length) {
  const c = css[i];

  /* Строка в кавычках — переносим как есть вместе с экранированием. */
  if (c === '"' || c === "'") {
    const quote = c;
    r += c; i++;
    while (i < css.length) {
      if (css[i] === '\\') { r += css[i] + (css[i + 1] || ''); i += 2; continue; }
      r += css[i];
      if (css[i] === quote) { i++; break; }
      i++;
    }
    continue;
  }

  /* Комментарий — выбрасываем целиком. */
  if (c === '/' && css[i + 1] === '*') {
    const end = css.indexOf('*/', i + 2);
    i = end === -1 ? css.length : end + 2;
    /* Комментарий часто стоит между правилами: чтобы селекторы не слиплись,
       оставляем на его месте один пробел — лишний уберёт следующий шаг. */
    r += ' ';
    continue;
  }

  /* Любая цепочка пробелов и переносов — один пробел. */
  if (/\s/.test(c)) {
    while (i < css.length && /\s/.test(css[i])) i++;
    r += ' ';
    continue;
  }

  r += c; i++;
}

/* Пробелы вокруг служебных знаков не нужны. Скобку в url() и знак в
   селекторах вроде a[href^=" "] мы уже прошли выше как строку. */
r = r
  .replace(/\s*([{}:;,>+~])\s*/g, '$1')
  .replace(/;}/g, '}')
  .trim();

/* calc() без пробелов вокруг + и - считается иначе — их мы не трогали
   намеренно, но проверим, что не осталось «calc(» со слипшимся знаком. */
if (/calc\([^)]*[0-9a-z%)]\s*[+\-]\s*[^)]*\)/i.test(css) && !/calc\([^)]*[+\-]/.test(r)) {
  console.error('ОШИБКА: из calc() пропали знаки, сжатие отменено');
  process.exit(1);
}

fs.writeFileSync(out, r);
const was = Buffer.byteLength(css), now = Buffer.byteLength(r);
console.log(path.basename(out) + ': ' + was + ' -> ' + now + ' б (' + Math.round((1 - now / was) * 100) + '% меньше)');
